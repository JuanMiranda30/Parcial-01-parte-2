# Par-Impar – Mayor-Número
# Estudiante 1: Juan Miranda

def par_impar(numero):
    if numero % 2 == 0:
        return "El número es PAR"
    else:
        return "El número es IMPAR"

print("Estudiante 1:", par_impar(8))


